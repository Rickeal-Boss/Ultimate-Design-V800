/**
 * R98 · 自由驾驶车身动态阻尼（独立于 FREE 标定表）。
 *
 * 为什么单独落一个文件：R96 已把 roll/pitch 的**幅值**标定到真车量级
 * （rollMaxRad 3.5°、pitchMaxRad 2.0°），R98 只改“回正快慢”这一件事。
 * 旧实现把阻尼写死在 FreeDrive.step() 的 `damp(..., 6, dt)` / `damp(..., 4, dt)`，
 * 时间常数分别只有 0.167s / 0.25s —— 车身像直接钉在路面上，转向/加速一停
 * 姿态立刻消失，缺少中大型行政旗舰该有的惯性余韵。
 *
 * 新值：roll 3.8（τ≈0.263s）、pitch 3.2（τ≈0.313s）。
 * 只影响视觉姿态收敛速度，不改 FREE 的 12 个漂移灵魂参数、不改纵向力、
 * 不改摩擦圆/限速/路障/热衰减/涡扇契约。
 */
export const FREE_BODY_DAMPING = Object.freeze({
  /** 侧倾回正阻尼（1/s）：6 → 3.8，车身横摆后保留更自然的余韵 */
  roll: 3.8,
  /** 俯仰回正阻尼（1/s）：4 → 3.2，加速抬头/刹车点头更沉稳 */
  pitch: 3.2
} as const);

/**
 * R126 · 撞墙姿态「被顶晃动」欠阻尼二阶通道（独立于 FREE_BODY_DAMPING 常态一阶）。
 *
 * 为什么：R99~R108 把撞墙姿态做成「一阶 damp 单调回正 + 一次性位置/速率冲量」，
 * 撞后车身**单调钉回**目标、永不过冲 ⇒ 读作「撞完瞬间稳定」而非真实碰撞的
 * 「被顶 → 回弹过冲 → 晃动 → 稳定」。真实车身悬架是欠阻尼二阶（簧上固有频率
 * ~1~1.5 Hz、ζ≈0.3~0.5），撞墙后应有一次清晰的回摆过冲。
 *
 * 本通道：撞墙帧一次性注入角速度（impactN 加权），随后按「弹簧-阻尼」二阶积分，
 * 过冲回摆一次再稳定 —— 只叠加在视觉姿态上，**常态一阶阻尼（FREE_BODY_DAMPING）
 * 零改、FREE 灵魂 12 / 摩擦圆 / 限速 / 漂移全部零改**。撞得越狠晃动越大（∝impactN），
 * 斜擦 fn 小晃动小（刮擦非硬撞）。
 *
 * 参数（数值探针 r126_second_order 标定）：
 *   omega=8 rad/s（簧上固有频率 ~1.27 Hz）、zeta=0.5（一次清晰回摆 ~16%，不失控）；
 *   gains 使正撞 20 m/s（impactN=20）俯仰/侧倾峰值 ≈0.030 rad（1.7°，≈0.86×灵魂上限，
 *   保留「被顶可感」且不越 clamp）。
 */
export const FREE_BODY_IMPACT_OSC = Object.freeze({
  /** 撞墙晃动固有角频率 rad/s（ω=8 ⇒ τ≈0.125s，簧上频率量级） */
  omega: 8,
  /** 阻尼比（0.5 ⇒ 一次过冲回摆 ~16%，ζ≥0.5 无持续振荡） */
  zeta: 0.5,
  /** 撞墙帧侧倾角速度注入增益 rad/s per m/s（侧倾方向 = 撞击法向侧） */
  rollGain: 0.022,
  /** 撞墙帧俯仰角速度注入增益 rad/s per m/s（负 = 车头朝墙面点头） */
  pitchGain: 0.022
} as const);
